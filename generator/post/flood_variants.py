"""flood_variants.py: a placeable class for every armed Flood form and gun it can carry (flood_arsenal.py gives every
armed body every gun but the Forerunners'). Run from generator/ after flood_arsenal.py:  python3 post/flood_variants.py

For each body (and Brute rank) in FORMS and each gun in GUNS that no generated class already carries, this writes
  * a class HCE_<prefix><suffix> : <the form's armed class> that takes the gun as it spawns (HCE_EquipGun: the
    loadout's firing data, animations and overlay model), with its Ultimate Doom Builder keys,
    into packs/HaloCE_Flood/ZScript/HaloCE/hce_flood_variants.zsc
  * its MODELDEF (the armed class's, renamed: MODELDEF isn't inherited) into packs/HaloCE_Flood/modeldef.hce_flood_variants
  * its editor number (from ED0 up) in a DoomEdNums block between the FLOOD VARIANTS markers in the Flood pack's mapinfo.txt
and puts "Any gun but the Forerunners'" in the bestiary's weapons column of the armed forms.
HDE only: the Standalone packs have no gun overlays (their enemies drop no guns). Runs again cleanly."""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__)); GEN = os.path.dirname(HERE)
FLOOD = os.path.join(GEN, '..', 'packs', 'HaloCE_Flood')
ZS = f'{FLOOD}/ZScript/HaloCE'
ED0 = 31000
# HDE gun class -> (class name suffix, editor title). Halo_MA5B is the Flood's own 'AssaultRifle', the MA37 is 'Ma37'
# as the Marines name it, the Magnum 'Pistol' as the Flood's own Magnum forms are named.
GUNS = [
    ('Halo_MA5B', 'AssaultRifle', 'Assault Rifle'), ('Halo_AssaultRifle', 'Ma37', 'MA37'),
    ('Halo_BattleRifle', 'BattleRifle', 'Battle Rifle'), ('Halo_BeamRifle', 'BeamRifle', 'Beam Rifle'),
    ('Halo_Bulldog', 'Bulldog', 'Bulldog'), ('Halo_Carbine', 'Carbine', 'Carbine'), ('Halo_Commando', 'Commando', 'Commando'),
    ('Halo_DBLShotgun', 'DoubleBarrel', 'Double Barrel'), ('Halo_DMR', 'Dmr', 'DMR'),
    ('Halo_Flamethrower', 'FlameThrower', 'Flamethrower'), ('Halo_FuelRod', 'FuelRod', 'Fuel Rod'), ('Halo_GPMG', 'Gpmg', 'GPMG'),
    ('Halo_GrenadeLauncher', 'GrenadeLauncher', 'Grenade Launcher'), ('Halo_Hydra', 'Hydra', 'Hydra'),
    ('Halo_Magnum', 'Pistol', 'Pistol'), ('Halo_Needler', 'Needler', 'Needler'), ('Halo_NeedlerJavelin', 'NeedlerJavelin', 'Needler Javelin'),
    ('Halo_PlasmaCaster', 'PlasmaCaster', 'Plasma Caster'), ('Halo_PlasmaPistol', 'PlasmaPistol', 'Plasma Pistol'),
    ('Halo_PlasmaRifle', 'PlasmaRifle', 'Plasma Rifle'), ('Halo_PulseCarbine', 'PulseCarbine', 'Pulse Carbine'),
    ('Halo_RocketLauncher', 'RocketLauncher', 'Rocket Launcher'), ('Halo_SMG', 'Smg', 'SMG'), ('Halo_Shotgun', 'Shotgun', 'Shotgun'),
    ('Halo_Sidekick', 'Sidekick', 'Sidekick'), ('Halo_SniperRifle', 'SniperRifle', 'Sniper Rifle'), ('Halo_Spiker', 'Spiker', 'Spiker'),
    ('Halo_StickyDetonator', 'StickyDetonator', 'Sticky Detonator'),
]
# form -> (class name prefix, the armed class it extends, its zsc, its modeldef)
H, D = 'hce_flood', 'dig_flood'
FORMS = [
    ('HCE_FloodcombatHuman', 'HCE_FloodcombatHumanAssaultRifle', H),
    ('HCE_FloodcombatHumanUnarmored', 'HCE_FloodcombatHumanUnarmoredAssaultRifle', H),
    ('HCE_FloodcombatHumanArmored', 'HCE_FloodcombatHumanArmoredAssaultRifle', H),
    ('HCE_FloodcombatOdst', 'HCE_FloodcombatOdstAssaultRifle', H),
    ('HCE_FloodcombatElite', 'HCE_FloodcombatEliteAssaultRifle', H),
    ('HCE_FloodcombatEliteMinor', 'HCE_FloodcombatEliteMinorPlasmaRifle', H),
    ('HCE_FloodcombatEliteMajor', 'HCE_FloodcombatEliteMajorPlasmaRifle', H),
    ('HCE_FloodcombatEliteUltra', 'HCE_FloodcombatEliteUltraFuelRod', H),
    ('HCE_FloodGrunt', 'HCE_FloodGruntPlasmaPistol', H),
    ('HCE_FloodcombatBruteMinor', 'HCE_FloodcombatBruteMinorAssaultRifle', D),
    ('HCE_FloodcombatBruteMajor', 'HCE_FloodcombatBruteMajorSpiker', D),
    ('HCE_FloodcombatBruteCaptain', 'HCE_FloodcombatBruteCaptainPlasmaRifle', D),
    ('HCE_FloodcombatBruteHonorGuard', 'HCE_FloodcombatBruteHonorGuardAssaultRifle', D),
]
BEGIN, END = '// ---- FLOOD VARIANTS (generator/post/flood_variants.py) ----\n', '// ---- FLOOD VARIANTS END ----\n'
ANY = "Any gun but the Forerunners'"


def existing():
    """the generated classes: name -> (its HCE_Drops gun, editor category, title, sprite)"""
    out = {}
    for f in (H, D):
        s = open(f'{ZS}/{f}.zsc').read()
        for m in re.finditer(r'\nclass (HCE_Flood\w+) : \w+\n\{(.*?)\n\}\n', s, re.S):
            g = lambda p: (re.search(p, m.group(2)) or [None, None])[1]
            out[m.group(1)] = (g(r'HCE_Drops "(\w+)"'), g(r'\$Category "([^"]+)"'), g(r'\$Title "([^"]+)"'), g(r'\$Sprite "(\w+)"'))
    return out


def modeldef(f, cls):
    s = open(f'{FLOOD}/modeldef.{f}').read()
    return re.search(r'^Model %s\n\{\n.*?^\}\n' % cls, s, re.S | re.M).group(0)


def main():
    have = existing()
    zs = ['// generated by generator/post/flood_variants.py: every armed Flood form with every gun it can carry (the\n'
          '// Flood arsenal, hce_flood_arsenal.zsc). Each takes its gun as it spawns; everything else is its armed class\'s.\n']
    md = ['// generated by generator/post/flood_variants.py: the Flood weapon variants (their armed classes\' models)\n']
    ed = []; n = ED0
    for prefix, parent, f in FORMS:
        _, cat, title, sprite = have[parent]
        base_title = re.sub(r' \(.*\)$', '', title)
        mdl = modeldef(f, parent)
        for gun, suf, gt in GUNS:
            cls = prefix + suf
            if cls in have: continue                 # the generated armed forms (the same names)
            zs.append(f'class {cls} : {parent}\n{{\n\t//$Category "{cat}"\n\t//$Title "{base_title} ({gt})"\n'
                      f'\t//$Sprite "{sprite}"\n'
                      f'\toverride void PostBeginPlay() {{ Super.PostBeginPlay(); HCE_EquipGun(\'{gun}\'); }}\n}}\n')
            md.append(mdl.replace(f'Model {parent}\n', f'Model {cls}\n', 1))
            ed.append(f'\t{n} = {cls}\n'); n += 1
    open(f'{ZS}/hce_flood_variants.zsc', 'w').write('\n'.join(zs))
    open(f'{FLOOD}/modeldef.hce_flood_variants', 'w').write(''.join(md))
    zt = f'{FLOOD}/zscript.txt'; s = open(zt).read(); inc = '#include "ZScript/HaloCE/hce_flood_variants.zsc"\n'
    if inc not in s: open(zt, 'w').write(s.rstrip('\n') + '\n' + inc)
    mi = f'{FLOOD}/mapinfo.txt'; s = open(mi).read()
    s = re.sub(re.escape(BEGIN) + '.*?' + re.escape(END), '', s, flags=re.S).rstrip('\n') + '\n'
    open(mi, 'w').write(s + '\n' + BEGIN + 'DoomEdNums\n{\n' + ''.join(ed) + '}\n' + END)
    bp = f'{FLOOD}/hcebest.flood'; lines = open(bp).read().split('\n')
    armed = {p for _, p, _ in FORMS} | {'HCE_FloodcombatEliteMajorNeedler', 'HCE_FloodcombatEliteMinorNeedler',
            'HCE_FloodcombatBruteMajorShotgun', 'HCE_FloodcombatBruteCaptainPlasmaRifle', 'HCE_FloodGrunt'}
    for i, l in enumerate(lines):
        c = l.split('\t')
        if c[0] == 'E' and len(c) >= 8 and c[1] in armed:
            c = c[:8] + [ANY]; lines[i] = '\t'.join(c)
    open(bp, 'w').write('\n'.join(lines))
    print(f'{n - ED0} variants ({ED0}..{n - 1})')


if __name__ == '__main__':
    main()
